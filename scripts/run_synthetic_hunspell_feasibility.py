#!/usr/bin/env python
"""Run the synthetic-only Hunspell expansion feasibility gate.

This command uses only invented fixtures and public tool sources. It never
accepts a corpus path, dictionary path, resource path, output path, subset, or
language-data argument. The real RLA-ES bundle, CALLHOME, and Bangor are outside
its interface and remain closed.

The command refuses by default. With the explicit opt-in it:

* downloads the official Hunspell 1.7.3 source archive and verifies the public
  digest reported by GitHub;
* compiles that source with networking disabled inside one platform-and-digest
  pinned ARM64 container;
* validates a small, invented Hunspell fixture before invoking upstream tools;
* runs ``wordforms`` serially in two separate, read-only, network-disabled
  containers, each with a private ``/tmp``;
* compares both generated byte streams with each other and with a fixed expected
  synthetic set;
* checks the same bounded universe with the pinned Hunspell executable; and
* prints one content-free JSON object containing public identities, aggregate
  counts, and Boolean gate results.

No lexical entry, generated form, source hash, local path, build log, or tool
diagnostic is printed. All working files are temporary and deleted on exit.
This is a feasibility harness, not the later RLA-ES generation driver.
"""

