def _write_fixture(fixture_dir: Path) -> None:
    fixture_dir.mkdir()
    expected_text = "".join(f"{word}\n" for word in _EXPECTED_FORMS)
    candidate_text = "".join(
        f"{word}\n" for word in sorted(_EXPECTED_FORMS + _REJECTED_FORMS)
    )
    rejected_text = "".join(f"{word}\n" for word in _REJECTED_FORMS)
    files = {
        "synthetic.aff": _AFFIX_TEXT,
        "synthetic.dic": _DICTIONARY_TEXT,
        "expected.txt": expected_text,
        "candidates.txt": candidate_text,
        "rejected.txt": rejected_text,
        "run_generation.sh": _GENERATION_SCRIPT,
    }
    for name, text in files.items():
        (fixture_dir / name).write_text(text, encoding="utf-8", newline="\n")
    (fixture_dir / "run_generation.sh").chmod(0o755)
    _validate_fixture_dir(fixture_dir)


def _alphabetic_id(index: int, *, width: int = 3) -> str:
    """Return a fixed-width lowercase identifier for invented scale entries."""
    if isinstance(index, bool) or type(index) is not int or not 0 <= index < 26**width:
        raise SyntheticFeasibilityError
    chars = ["a"] * width
    remaining = index
    for position in range(width - 1, -1, -1):
        remaining, digit = divmod(remaining, 26)
        chars[position] = chr(ord("a") + digit)
    return "".join(chars)


def _write_scale_fixture(fixture_dir: Path) -> None:
    """Create a bounded invented dictionary for repeated wordforms execution."""
    fixture_dir.mkdir()
    bases = tuple(
        f"synscale{_alphabetic_id(index)}" for index in range(_SCALE_BASE_COUNT)
    )
    expected = tuple(sorted((*bases, *(f"{word}x" for word in bases))))
    rejected = ("synscalezzzz",)
    candidates = tuple(sorted((*expected, *rejected)))
    dictionary = f"{len(bases)}\n" + "".join(f"{word}/A\n" for word in bases)
    affix = "SET UTF-8\nFLAG UTF-8\nSFX A Y 1\nSFX A 0 x .\n"
    files = {
        "synthetic.aff": affix,
        "synthetic.dic": dictionary,
        "expected.txt": "".join(f"{word}\n" for word in expected),
        "candidates.txt": "".join(f"{word}\n" for word in candidates),
        "rejected.txt": "".join(f"{word}\n" for word in rejected),
        "run_generation.sh": _GENERATION_SCRIPT,
    }
    for name, text in files.items():
        (fixture_dir / name).write_text(text, encoding="utf-8", newline="\n")
    (fixture_dir / "run_generation.sh").chmod(0o755)
    _validate_fixture_dir(fixture_dir)


def _run(command: list[str], *, timeout: int = 300) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            command,
            check=True,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except (OSError, subprocess.SubprocessError):
        raise SyntheticFeasibilityError from None


def _download_source(archive_path: Path) -> None:
    try:
        with urllib.request.urlopen(HUNSPELL_ARCHIVE_URL, timeout=60) as response:
            data = response.read()
    except (OSError, TimeoutError):
        raise SyntheticFeasibilityError from None
    if hashlib.sha256(data).hexdigest() != HUNSPELL_ARCHIVE_SHA256:
        raise SyntheticFeasibilityError
    archive_path.write_bytes(data)


def _extract_source(archive_path: Path, destination: Path) -> Path:
    try:
        with tarfile.open(archive_path, "r:gz") as archive:
            members = archive.getmembers()
            for member in members:
                relative = PurePosixPath(member.name)
                if relative.is_absolute() or ".." in relative.parts:
                    raise SyntheticFeasibilityError
                if not (member.isdir() or member.isfile()):
                    raise SyntheticFeasibilityError
            archive.extractall(destination, members=members, filter="data")
    except (OSError, tarfile.TarError):
        raise SyntheticFeasibilityError from None
    source_dir = destination / "hunspell-1.7.3"
    if source_dir.is_symlink() or not source_dir.is_dir():
        raise SyntheticFeasibilityError
    if not (source_dir / "configure").is_file():
        raise SyntheticFeasibilityError
    if not (source_dir / "src" / "tools" / "wordforms").is_file():
        raise SyntheticFeasibilityError
    return source_dir


def _base_docker_args() -> list[str]:
    return [
        "docker",
        "run",
        "--rm",
        "--network",
        "none",
        "--platform",
        CONTAINER_PLATFORM,
        "--read-only",
        "--cap-drop",
        "ALL",
        "--security-opt",
        "no-new-privileges",
        "--tmpfs",
        "/tmp:rw,nosuid,nodev,noexec,size=64m",
        "-e",
        "LANG=C.UTF-8",
        "-e",
        "LC_ALL=C.UTF-8",
    ]


def _build_hunspell(source_dir: Path, install_dir: Path) -> None:
    install_dir.mkdir()
    _run(["docker", "pull", "--platform", CONTAINER_PLATFORM, CONTAINER_REFERENCE])
    command = _base_docker_args() + [
        "--mount",
        f"type=bind,src={source_dir},dst=/src",
        "--mount",
        f"type=bind,src={install_dir},dst=/install",
        "-w",
        "/src",
        CONTAINER_REFERENCE,
        "bash",
        "-lc",
        "./configure --prefix=/install >/tmp/configure.log 2>&1 "
        "&& make -j2 >/tmp/make.log 2>&1 "
        "&& make install >/tmp/install.log 2>&1 "
        "&& test -x /install/bin/hunspell "
        "&& test -x /install/bin/wordforms",
    ]
    _run(command)


def _inspect_environment(install_dir: Path) -> dict[str, str]:
    script = r"""
set -euo pipefail
export PATH=/opt/hunspell/bin:$PATH
export LD_LIBRARY_PATH=/opt/hunspell/lib
. /etc/os-release
printf 'architecture=%s\n' "$(uname -m)"
printf 'os=%s:%s\n' "$ID" "$VERSION_ID"
printf 'bash=%s\n' "$BASH_VERSION"
printf 'grep=%s\n' "$(grep --version | head -n1 | awk '{print $NF}')"
printf 'awk=%s\n' "$(awk -W version 2>&1 | head -n1 | awk '{print $2}')"
printf 'sort=%s\n' "$(sort --version | head -n1 | awk '{print $NF}')"
printf 'locale=%s\n' "$(locale charmap)"
printf 'gcc=%s\n' "$(gcc -dumpfullversion)"
printf 'gxx=%s\n' "$(g++ -dumpfullversion)"
printf 'make=%s\n' "$(make --version | head -n1 | awk '{print $3}')"
hunspell_version="$(hunspell --version | head -n1 \
    | sed -n 's/.*Hunspell \([0-9.]*\)).*/\1/p')"
printf 'hunspell=%s\n' "$hunspell_version"
test -x /opt/hunspell/bin/wordforms
printf 'wordforms_installed=true\n'
"""
    command = _base_docker_args() + [
        "--mount",
        f"type=bind,src={install_dir},dst=/opt/hunspell,readonly",
        CONTAINER_REFERENCE,
        "bash",
        "-lc",
        script,
    ]
    result = _run(command)
    observed: dict[str, str] = {}
    for line in result.stdout.splitlines():
        if "=" not in line:
            raise SyntheticFeasibilityError
        key, value = line.split("=", 1)
        if key in observed or not key or not value:
            raise SyntheticFeasibilityError
        observed[key] = value
    if observed != _EXPECTED_ENVIRONMENT:
        raise SyntheticFeasibilityError
    return observed


def _run_generation(fixture_dir: Path, install_dir: Path, output_dir: Path) -> None:
    output_dir.mkdir()
    command = _base_docker_args() + [
        "--mount",
        f"type=bind,src={fixture_dir},dst=/fixture,readonly",
        "--mount",
        f"type=bind,src={install_dir},dst=/opt/hunspell,readonly",
        "--mount",
        f"type=bind,src={output_dir},dst=/output",
        "-w",
        "/fixture",
        CONTAINER_REFERENCE,
        "bash",
        "/fixture/run_generation.sh",
    ]
    _run(command)


def _expect_closed_failure(operation) -> bool:
    try:
        operation()
    except SyntheticFeasibilityError:
        return True
    return False


def _exercise_fixture_failures(root: Path, fixture_dir: Path) -> dict[str, bool]:
    results: dict[str, bool] = {}

    def variant(name: str) -> Path:
        target = root / name
        shutil.copytree(fixture_dir, target)
        return target

    missing_aff = variant("missing_aff")
    (missing_aff / "synthetic.aff").unlink()
    results["missing_affix_failed_closed"] = _expect_closed_failure(
        lambda: _validate_fixture_dir(missing_aff)
    )

    missing_dic = variant("missing_dic")
    (missing_dic / "synthetic.dic").unlink()
    results["missing_dictionary_failed_closed"] = _expect_closed_failure(
        lambda: _validate_fixture_dir(missing_dic)
    )

    malformed_aff = variant("malformed_aff")
    (malformed_aff / "synthetic.aff").write_text(
        _AFFIX_TEXT.replace("PFX A Y 1", "PFX A Y 2"), encoding="utf-8", newline="\n"
    )
    results["malformed_affix_failed_closed"] = _expect_closed_failure(
        lambda: _validate_fixture_dir(malformed_aff)
    )

    malformed_dic = variant("malformed_dic")
    (malformed_dic / "synthetic.dic").write_text(
        _DICTIONARY_TEXT.replace("6\n", "7\n", 1), encoding="utf-8", newline="\n"
    )
    results["malformed_dictionary_failed_closed"] = _expect_closed_failure(
        lambda: _validate_fixture_dir(malformed_dic)
    )

    unsupported_flag = variant("unsupported_flag")
    (unsupported_flag / "synthetic.aff").write_text(
        _AFFIX_TEXT.replace("FLAG UTF-8", "FLAG long"), encoding="utf-8", newline="\n"
    )
    results["unsupported_flag_mode_failed_closed"] = _expect_closed_failure(
        lambda: _validate_fixture_dir(unsupported_flag)
    )

    unsupported_directive = variant("unsupported_directive")
    (unsupported_directive / "synthetic.aff").write_text(
        _AFFIX_TEXT + "COMPLEXPREFIXES\n", encoding="utf-8", newline="\n"
    )
    results["unsupported_directive_failed_closed"] = _expect_closed_failure(
        lambda: _validate_fixture_dir(unsupported_directive)
    )
    if not all(results.values()):
        raise SyntheticFeasibilityError
    return results


def _read_output(path: Path) -> bytes:
    if path.is_symlink() or not path.is_file():
        raise SyntheticFeasibilityError
    try:
        data = path.read_bytes()
    except OSError:
        raise SyntheticFeasibilityError from None
    if not data or not data.endswith(b"\n") or b"\r" in data or b"\x00" in data:
        raise SyntheticFeasibilityError
    return data


def _execute() -> dict[str, object]:
    with tempfile.TemporaryDirectory(prefix="neu-lab-hunspell-synthetic-") as raw_root:
        root = Path(raw_root)
        archive_path = root / HUNSPELL_ARCHIVE_NAME
        _download_source(archive_path)
        source_dir = _extract_source(archive_path, root / "source")

        fixture_dir = root / "fixture"
        _write_fixture(fixture_dir)
        failure_results = _exercise_fixture_failures(root, fixture_dir)

        install_dir = root / "install"
        _build_hunspell(source_dir, install_dir)
        _inspect_environment(install_dir)

        run_one = root / "run_one"
        run_two = root / "run_two"
        _run_generation(fixture_dir, install_dir, run_one)
        _run_generation(fixture_dir, install_dir, run_two)

        expected = (fixture_dir / "expected.txt").read_bytes()
        rejected = (fixture_dir / "rejected.txt").read_bytes()
        generated_one = _read_output(run_one / "generated.txt")
        generated_two = _read_output(run_two / "generated.txt")
        accepted_one = _read_output(run_one / "accepted.txt")
        accepted_two = _read_output(run_two / "accepted.txt")
        rejected_one = _read_output(run_one / "rejected.txt")
        rejected_two = _read_output(run_two / "rejected.txt")

        two_runs_identical = generated_one == generated_two
        expected_match = generated_one == expected
        direct_parity = accepted_one == expected and accepted_two == expected
        rejected_match = rejected_one == rejected and rejected_two == rejected
        if not all((two_runs_identical, expected_match, direct_parity, rejected_match)):
            raise SyntheticFeasibilityError

        scale_fixture = root / "scale_fixture"
        _write_scale_fixture(scale_fixture)
        scale_run_one = root / "scale_run_one"
        scale_run_two = root / "scale_run_two"
        _run_generation(scale_fixture, install_dir, scale_run_one)
        _run_generation(scale_fixture, install_dir, scale_run_two)
        scale_expected = (scale_fixture / "expected.txt").read_bytes()
        scale_generated_one = _read_output(scale_run_one / "generated.txt")
        scale_generated_two = _read_output(scale_run_two / "generated.txt")
        scale_accepted_one = _read_output(scale_run_one / "accepted.txt")
        scale_accepted_two = _read_output(scale_run_two / "accepted.txt")
        scale_identical = scale_generated_one == scale_generated_two
        scale_expected_match = scale_generated_one == scale_expected
        scale_parity = (
            scale_accepted_one == scale_expected and scale_accepted_two == scale_expected
        )
        if not all((scale_identical, scale_expected_match, scale_parity)):
            raise SyntheticFeasibilityError

        summary: dict[str, object] = {
            "hunspell_release": HUNSPELL_RELEASE,
            "hunspell_commit": HUNSPELL_COMMIT,
            "container_platform": CONTAINER_PLATFORM,
            "environment_identity_match": True,
            "offline_build": True,
            "synthetic_generation_runs": 2,
            "generated_entry_count": len(_EXPECTED_FORMS),
            "two_runs_byte_identical": True,
            "expected_set_match": True,
            "direct_hunspell_parity": True,
            "rejected_form_rejected": True,
            "scale_probe_base_count": _SCALE_BASE_COUNT,
            "scale_probe_generated_entry_count": _SCALE_BASE_COUNT * 2,
            "scale_probe_two_runs_byte_identical": True,
            "scale_probe_expected_set_match": True,
            "scale_probe_direct_hunspell_parity": True,
            **failure_results,
            "no_real_resource_or_corpus_access": True,
        }
        if tuple(summary) != SUMMARY_KEYS:
            raise SyntheticFeasibilityError
        return summary


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run the invented-fixture Hunspell feasibility gate."
    )
    parser.add_argument(
        "--allow-synthetic-hunspell-run",
        action="store_true",
        help="explicitly allow the temporary public-source and invented-fixture run",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    if not args.allow_synthetic_hunspell_run:
        print(_OPT_IN_MESSAGE, file=sys.stderr)
        return EXIT_OPT_IN_REQUIRED
    try:
        summary = _execute()
    except Exception:
        print(_ABORT_MESSAGE, file=sys.stderr)
        return EXIT_OPERATIONAL_ABORT
    print(json.dumps(summary, ensure_ascii=True, separators=(",", ":")))
    return EXIT_SUCCESS


if __name__ == "__main__":
    raise SystemExit(main())
