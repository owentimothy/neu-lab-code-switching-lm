class SyntheticFeasibilityError(RuntimeError):
    """Any fail-closed synthetic environment or fixture failure."""


def _fixed_lines(path: Path) -> list[str]:
    """Read a strict UTF-8/LF text file without returning path-bearing errors."""
    if path.is_symlink() or not path.is_file():
        raise SyntheticFeasibilityError
    try:
        data = path.read_bytes()
        text = data.decode("utf-8", errors="strict")
    except (OSError, UnicodeError):
        raise SyntheticFeasibilityError from None
    if not data or not data.endswith(b"\n") or b"\r" in data or b"\x00" in data:
        raise SyntheticFeasibilityError
    lines = text.splitlines()
    if not lines or any(not line or line != line.strip() for line in lines):
        raise SyntheticFeasibilityError
    return lines


def _parse_affix(path: Path) -> frozenset[str]:
    """Validate the deliberately narrow invented affix fixture.

    This is not an RLA-ES parser. It recognizes only the small PFX/SFX subset
    needed by this synthetic proof and rejects every unreviewed directive or
    flag mode rather than silently ignoring it.
    """
    lines = _fixed_lines(path)
    if lines[:2] != ["SET UTF-8", "FLAG UTF-8"]:
        raise SyntheticFeasibilityError

    headers: dict[tuple[str, str], tuple[str, int]] = {}
    observed_rules: dict[tuple[str, str], int] = {}
    for line in lines[2:]:
        parts = line.split()
        if not parts or parts[0] not in {"PFX", "SFX"}:
            raise SyntheticFeasibilityError
        if len(parts) == 4 and parts[2] in {"Y", "N"} and parts[3].isdigit():
            kind, flag = parts[:2]
            if not re.fullmatch(r"[A-Z]", flag):
                raise SyntheticFeasibilityError
            key = (kind, flag)
            if key in headers:
                raise SyntheticFeasibilityError
            headers[key] = (parts[2], int(parts[3]))
            observed_rules[key] = 0
            continue
        if len(parts) != 5:
            raise SyntheticFeasibilityError
        kind, flag, strip, add, condition = parts
        key = (kind, flag)
        if key not in headers:
            raise SyntheticFeasibilityError
        tokens = (strip, add, condition)
        if not all(
            token and not any(char.isspace() for char in token) for token in tokens
        ):
            raise SyntheticFeasibilityError
        observed_rules[key] += 1

    if not headers:
        raise SyntheticFeasibilityError
    for key, (_, expected_count) in headers.items():
        if observed_rules[key] != expected_count:
            raise SyntheticFeasibilityError
    flags = [flag for _, flag in headers]
    if len(flags) != len(set(flags)):
        raise SyntheticFeasibilityError
    return frozenset(flags)


def _parse_dictionary(path: Path, *, allowed_flags: frozenset[str]) -> tuple[str, ...]:
    lines = _fixed_lines(path)
    if not lines[0].isdigit():
        raise SyntheticFeasibilityError
    entries = lines[1:]
    if int(lines[0]) != len(entries) or not entries:
        raise SyntheticFeasibilityError

    words: list[str] = []
    for entry in entries:
        match = _SAFE_ENTRY_RE.fullmatch(entry)
        if match is None:
            raise SyntheticFeasibilityError
        word = match.group("word")
        flags = match.group("flags") or ""
        if len(flags) != len(set(flags)) or not set(flags) <= allowed_flags:
            raise SyntheticFeasibilityError
        words.append(word)
    if len(words) != len(set(words)):
        raise SyntheticFeasibilityError
    return tuple(words)


def _validate_word_list(path: Path) -> tuple[str, ...]:
    lines = _fixed_lines(path)
    if any(_SAFE_WORD_RE.fullmatch(line) is None for line in lines):
        raise SyntheticFeasibilityError
    if lines != sorted(set(lines)):
        raise SyntheticFeasibilityError
    return tuple(lines)


def _validate_fixture_dir(fixture_dir: Path) -> None:
    if fixture_dir.is_symlink() or not fixture_dir.is_dir():
        raise SyntheticFeasibilityError
    try:
        present = {entry.name for entry in fixture_dir.iterdir()}
    except OSError:
        raise SyntheticFeasibilityError from None
    if present != _FIXTURE_FILENAMES:
        raise SyntheticFeasibilityError
    if any(entry.is_symlink() or not entry.is_file() for entry in fixture_dir.iterdir()):
        raise SyntheticFeasibilityError

    allowed_flags = _parse_affix(fixture_dir / "synthetic.aff")
    dictionary_words = _parse_dictionary(
        fixture_dir / "synthetic.dic", allowed_flags=allowed_flags
    )
    expected = _validate_word_list(fixture_dir / "expected.txt")
    candidates = _validate_word_list(fixture_dir / "candidates.txt")
    rejected = _validate_word_list(fixture_dir / "rejected.txt")
    if not set(dictionary_words) <= set(expected):
        raise SyntheticFeasibilityError
    if set(candidates) != set(expected) | set(rejected):
        raise SyntheticFeasibilityError
    if set(expected) & set(rejected):
        raise SyntheticFeasibilityError


