def test_live_identity_accepts_only_exact_public_metadata():
    release = {
        "tag_name": runner.RESOURCE_RELEASE,
        "assets": [
            {
                "id": runner.RESOURCE_ASSET_ID,
                "name": runner.RESOURCE_ASSET_NAME,
                "size": runner.RESOURCE_ASSET_SIZE,
                "content_type": runner.RESOURCE_ASSET_CONTENT_TYPE,
                "browser_download_url": runner.RESOURCE_ASSET_URL,
                "digest": "sha256:" + "a" * 64,
            }
        ],
    }
    tag_ref = {
        "object": {"type": "tag", "sha": runner.RESOURCE_TAG_OBJECT}
    }
    tag = {
        "sha": runner.RESOURCE_TAG_OBJECT,
        "object": {"type": "commit", "sha": runner.RESOURCE_SOURCE_COMMIT},
    }
    identity = runner._verify_live_identity(release, tag_ref, tag)
    assert identity.download_url == runner.RESOURCE_ASSET_URL
    assert identity.publisher_digest == "sha256:" + "a" * 64


