def test_docker_generation_is_offline_read_only_and_narrowly_mounted(
    tmp_path, monkeypatch
):
    fixture = tmp_path / "fixture"
    install = tmp_path / "install"
    output = tmp_path / "output"
    fixture.mkdir()
    install.mkdir()
    captured: list[str] = []

    def fake_run(command, *, timeout=900):
        captured.extend(command)
        return None

    monkeypatch.setattr(runner, "_run", fake_run)
    runner._run_generation(fixture, install, output)
    mounts = [captured[index + 1] for index, value in enumerate(captured) if value == "--mount"]
    assert captured[captured.index("--network") + 1] == "none"
    assert "--read-only" in captured
    assert captured[captured.index("--platform") + 1] == "linux/arm64"
    assert len(mounts) == 3
    assert any("dst=/fixture,readonly" in mount for mount in mounts)
    assert any("dst=/opt/hunspell,readonly" in mount for mount in mounts)
    assert any("dst=/output" in mount and "readonly" not in mount for mount in mounts)


