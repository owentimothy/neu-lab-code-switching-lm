"""Synthetic-only tests for the private RLA-ES bundle builder.

The tests use invented dictionary, affix, notice, archive, and generated bytes.
They do not use Docker, the network, RLA-ES, CALLHOME, Bangor, ignored resources,
or private logs.
"""

from __future__ import annotations

