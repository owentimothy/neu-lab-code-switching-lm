import pytest

from cslm.utils.paths import project_root

_SCRIPT_PATH = project_root() / "scripts" / "build_spanish_rla_es_bundle.py"


def _load_script():
    spec = importlib.util.spec_from_file_location(
        "build_spanish_rla_es_bundle", _SCRIPT_PATH
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


runner = _load_script()

_SYNTHETIC_AFFIX = b"""SET UTF-8
FLAG UTF-8
PFX A Y 1
PFX A 0 syn .
SFX B Y 1
SFX B 0 z .
"""
_SYNTHETIC_DICTIONARY = b"""3
fakebase/A
invented/B
mockword/AB
"""


def _package_bytes(
    *,
    affix: bytes = _SYNTHETIC_AFFIX,
    dictionary: bytes = _SYNTHETIC_DICTIONARY,
    extra: bool = True,
) -> bytes:
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("es.dic", dictionary)
        archive.writestr("es.aff", affix)
        for name in runner.NOTICE_FILENAMES:
            archive.writestr(name, f"invented notice for {name}\n".encode())
        if extra:
            archive.writestr("META-INF/manifest.xml", b"invented metadata\n")
    return output.getvalue()


def _extraction(tmp_path: Path):
    return runner._extract_approved_members(_package_bytes(), tmp_path / "extracted")


